void	*ft_memchr(const void *s, int c, size_t n)
{
	unsigned char	*p;

	p = (unsigned char *) s;
	while (n > 0)
	{
		if (*p == c)
			return ((unsigned char *) p);
		p++;
		n--;
	}
	return (NULL);
}
